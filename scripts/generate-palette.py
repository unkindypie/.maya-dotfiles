#!/usr/bin/env python3
"""Generate tiny native color includes from the shared palette; no dependencies."""
from pathlib import Path
import argparse, json, re


def render(root):
    base = root / 'home/.config/maya-theme'
    palette = json.loads((base / 'palette.json').read_text())
    colors = palette['colors']
    for name, value in colors.items():
        if not re.fullmatch(r'[a-z][a-z0-9_]*', name) or not re.fullmatch(r'#[0-9a-fA-F]{6}(?:[0-9a-fA-F]{2})?', value):
            raise ValueError(f'Invalid palette entry: {name}')
    seen = {}
    for name, value in colors.items():
        normalized = value.lower()
        if normalized.endswith('ff') and len(normalized) == 9:
            normalized = normalized[:-2]
        if normalized in seen:
            raise ValueError(f'Duplicate palette colors: {seen[normalized]} and {name}; reuse one name')
        seen[normalized] = name
    def native(value):
        return ('rgb(' if len(value) == 7 else 'rgba(') + value[1:] + ')'
    def css(value):
        if len(value) == 7: return value
        return 'rgba({}, {}, {}, {:.8f})'.format(*(int(value[i:i+2], 16) for i in (1,3,5)), int(value[7:9], 16)/255)
    header = '# Generated by scripts/generate-palette.py; edit palette.json instead.\n'
    css_text = '/* Generated from maya-theme/palette.json. Do not edit. */\n' + ''.join(f'@define-color maya_{n} {css(v)};\n' for n,v in colors.items())
    conf = header + ''.join(f'$maya_{n} = {native(v)}\n' for n,v in colors.items())
    conf += '$maya_password_placeholder = <span foreground="#' + colors['faint_ink'] + '">Password</span>\n'
    conf += '$maya_password_failure = <span foreground="#' + colors['failure_ink'] + '">Try again ($ATTEMPTS)</span>\n'
    rasi = '/* Generated from maya-theme/palette.json. Do not edit. */\n* {\n' + ''.join(f'    maya-{n.replace(chr(95), chr(45))}: {css(v)};\n' for n,v in colors.items()) + '}\n'
    rasi = rasi[:-2] + '    maya-title-gradient: linear-gradient(to bottom, ' + colors['paper_white'] + ', ' + colors['title_gradient_end'] + ');\n}\n'
    lua = '-- Generated from palette.json. Do not edit.\nreturn {\n' + ''.join(f'  {n} = "{native(v)}",\n' for n,v in colors.items()) + '}\n'
    kitty = header
    for option, name in palette['kitty'].items():
        if not re.fullmatch(r'(background|foreground|cursor|selection_background|selection_foreground|color(?:[0-9]|1[0-5]))', option):
            raise ValueError(f'Invalid Kitty option: {option}')
        if len(colors[name]) != 7:
            raise ValueError(f'Kitty requires an opaque color: {name}')
        kitty += f'{option} {colors[name]}\n'
    wofi_path = root / 'home/.config/wofi/style.css'
    wofi_body = wofi_path.read_text()
    wofi_body = re.sub(r'/\* BEGIN GENERATED PALETTE \*/.*?/\* END GENERATED PALETTE \*/\n*', '', wofi_body, flags=re.S)
    wofi_body = wofi_body.removeprefix('@import "palette.css";\n').lstrip('\n')
    wofi = '/* BEGIN GENERATED PALETTE */\n' + css_text + '/* END GENERATED PALETTE */\n\n' + wofi_body
    return {
        'home/.config/waybar/palette.css': css_text,
        'home/.config/wofi/style.css': wofi,
        'home/.config/rofi/themes/maya-palette.rasi': rasi,
        'home/.config/maya-theme/colors.conf': conf,
        'home/.config/maya-theme/colors.lua': lua,
        'home/.config/maya-theme/kitty.conf': kitty,
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Fail if generated includes are stale')
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    stale = []
    for name, content in render(root).items():
        path = root / name
        if path.is_file() and path.read_text() == content: continue
        if args.check: stale.append(name)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if stale: raise SystemExit('Run python3 scripts/generate-palette.py; stale includes: ' + ', '.join(stale))
    print('Palette includes checked' if args.check else 'Palette includes generated; reload apps to apply')


if __name__ == '__main__': main()
