#!/usr/bin/env python3
"""Generate tiny native color includes from the shared palette; no dependencies."""
from pathlib import Path
import argparse, json, re, math, itertools


def oklab(color):
    """Convert opaque sRGB to Oklab for a conservative near-color audit."""
    rgb = [int(color[i:i+2], 16) / 255 for i in (1, 3, 5)]
    r, g, b = [v / 12.92 if v <= 0.04045 else ((v + 0.055) / 1.055) ** 2.4 for v in rgb]
    l = (0.4122214708*r + 0.5363325363*g + 0.0514459929*b) ** (1/3)
    m = (0.2119034982*r + 0.6806995451*g + 0.1073969566*b) ** (1/3)
    t = (0.0883024619*r + 0.2817188376*g + 0.6299787005*b) ** (1/3)
    return (0.2104542553*l + 0.793617785*m - 0.0040720468*t,
            1.9779984951*l - 2.428592205*m + 0.4505937099*t,
            0.0259040371*l + 0.7827717662*m - 0.808675766*t)


def near_colors(colors, threshold=0.02):
    # Different alpha levels are intentional and must not be merged as RGB twins.
    opaque = [(name, value) for name, value in colors.items() if len(value) == 7]
    return [(a, b, math.dist(oklab(x), oklab(y)))
            for (a, x), (b, y) in itertools.combinations(opaque, 2)
            if math.dist(oklab(x), oklab(y)) < threshold]


def render(root):
    base = root / 'color-palette'
    palette = json.loads((base / 'palette.json').read_text())
    colors = palette['colors']
    for name, value in colors.items():
        if not re.fullmatch(r'[a-z][a-z0-9_]*', name) or not re.fullmatch(r'#[0-9a-fA-F]{6}(?:[0-9a-fA-F]{2})?', value):
            raise ValueError(f'Invalid palette entry: {name}')
    seen = {}
    for name, value in colors.items():
        normalized = value.lower()
        if normalized.endswith('ff') and len(normalized) == 9:
            normalized = normalized[:-2]
        if normalized in seen:
            raise ValueError(f'Duplicate palette colors: {seen[normalized]} and {name}; reuse one name')
        seen[normalized] = name
    exceptions = {frozenset(item['colors']) for item in palette.get('similarity_exceptions', [])}
    for a, b, distance in near_colors(colors):
        if frozenset((a, b)) not in exceptions:
            raise ValueError(f'Near-duplicate colors: {a} / {b} (Oklab distance {distance:.4f}); reuse a color or document why it must differ')
    def native(value):
        return ('rgb(' if len(value) == 7 else 'rgba(') + value[1:] + ')'
    def css(value):
        if len(value) == 7: return value
        return 'rgba({}, {}, {}, {:.8f})'.format(*(int(value[i:i+2], 16) for i in (1,3,5)), int(value[7:9], 16)/255)
    header = '# Generated by scripts/generate-palette.py; edit palette.json instead.\n'
    css_text = '/* Generated from color-palette/palette.json. Do not edit. */\n' + ''.join(f'@define-color maya_{n} {css(v)};\n' for n,v in colors.items())
    conf = header + ''.join(f'$maya_{n} = {native(v)}\n' for n,v in colors.items())
    conf += '$maya_password_placeholder = <span foreground="#' + colors['faint_ink'] + '">Password</span>\n'
    conf += '$maya_password_failure = <span foreground="#' + colors['failure_ink'] + '">Try again ($ATTEMPTS)</span>\n'
    rasi = '/* Generated from color-palette/palette.json. Do not edit. */\n* {\n' + ''.join(f'    maya-{n.replace(chr(95), chr(45))}: {css(v)};\n' for n,v in colors.items()) + '}\n'
    rasi = rasi[:-2] + '    maya-title-gradient: linear-gradient(to bottom, ' + colors['paper_white'] + ', ' + colors['title_gradient_end'] + ');\n}\n'
    lua = '-- Generated from palette.json. Do not edit.\nreturn {\n' + ''.join(f'  {n} = "{native(v)}",\n' for n,v in colors.items()) + '}\n'
    kitty = header
    for option, name in palette['kitty'].items():
        if not re.fullmatch(r'(background|foreground|cursor|selection_background|selection_foreground|color(?:[0-9]|1[0-5]))', option):
            raise ValueError(f'Invalid Kitty option: {option}')
        if len(colors[name]) != 7:
            raise ValueError(f'Kitty requires an opaque color: {name}')
        kitty += f'{option} {colors[name]}\n'
    btop = '# Generated from color-palette/palette.json. Do not edit.\n# Maya Paper: dark ink and muted accents for cream terminals.\n'
    for option, name in palette.get('btop', {}).items():
        if not re.fullmatch(r'[a-z][a-z0-9_]*', option) or len(colors[name]) != 7:
            raise ValueError(f'Invalid btop color: {option}')
        btop += f'theme[{option}]="{colors[name]}"\n'
    wofi_path = root / 'home/.config/wofi/style.css'
    wofi_body = wofi_path.read_text()
    wofi_body = re.sub(r'/\* BEGIN GENERATED PALETTE \*/.*?/\* END GENERATED PALETTE \*/\n*', '', wofi_body, flags=re.S)
    wofi_body = wofi_body.removeprefix('@import "palette.css";\n').lstrip('\n')
    wofi = '/* BEGIN GENERATED PALETTE */\n' + css_text + '/* END GENERATED PALETTE */\n\n' + wofi_body
    return {
        'home/.config/waybar/palette.css': css_text,
        'home/.config/swaync/palette.css': css_text,
        'home/.config/wofi/style.css': wofi,
        'home/.config/rofi/themes/maya-palette.rasi': rasi,
        'color-palette/colors.conf': conf,
        'color-palette/colors.lua': lua,
        'color-palette/kitty.conf': kitty,
        'home/.config/btop/themes/maya-paper.theme': btop,
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Fail if generated includes are stale')
    parser.add_argument('--audit', action='store_true', help='Report retained near-color pairs and their reasons')
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    if args.audit:
        data = json.loads((root / 'color-palette/palette.json').read_text())
        reasons = {frozenset(item['colors']): item['reason'] for item in data.get('similarity_exceptions', [])}
        render(root)  # Validate exact and near-duplicate policies too.
        print(f"{len(data['colors'])} colors; near-color review:")
        for a, b, distance in near_colors(data['colors']):
            print(f'{a} / {b}: {distance:.4f} — {reasons[frozenset((a, b))]}')
        return
    stale = []
    for name, content in render(root).items():
        path = root / name
        if path.is_file() and path.read_text() == content: continue
        if args.check: stale.append(name)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if stale: raise SystemExit('Run python3 scripts/generate-palette.py; stale includes: ' + ', '.join(stale))
    print('Palette includes checked' if args.check else 'Palette includes generated; reload apps to apply')


if __name__ == '__main__': main()
